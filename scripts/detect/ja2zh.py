# GBK で表せても簡体字中国語では使わない字の検出網。
# JA2ZH（自動修正対象）と FLAG_ONLY（検出のみ）の和集合。
# 人名に使う字は作品の人物表と連動して除外する（ここに固有名詞は書かない）。
EXTRA_NON_GB = "".join(sorted(set(JA2ZH) | set(FLAG_ONLY)))

# 繁体字（または日本語旧字体）の代表字。簡体字訳に残れば疑い。
# lang/zh.py の _TRAD_MARKERS と同じ字種。
TRAD_MARKERS = "們這說學對頭車東長門見後發經過還動進會來開種樣點為問時沒讓邊務記讀覽術張應變兩風"


def count_chars(text: str, pred) -> list[tuple[str, int]]:
    counts: dict[str, int] = {}
    for ch in text:
        if ch in _ALLOW or not pred(ch):
            continue
        counts[ch] = counts.get(ch, 0) + 1
    return sorted(counts.items(), key=lambda kv: -kv[1])


def find_kana(text: str) -> list[tuple[str, int]]:
    """仮名の残り。"""
    return count_chars(text, lambda ch: bool(_KANA_RE.match(ch)))


def find_jp_quotes(text: str) -> list[tuple[str, int]]:
    """日本語の鉤括弧の残り（“ ” へ置換されていない）。"""
    return count_chars(text, lambda ch: ch in "「」『』")


def find_trad_markers(text: str) -> list[tuple[str, int]]:
    """繁体字・日本語旧字体の代表字。"""
    return count_chars(text, lambda ch: ch in TRAD_MARKERS)


def find_vfm(text: str) -> list[str]:
    """VFM ルビ括弧 {漢字|かな} の残り。"""
    return [m.group(0) for m in VFM.finditer(text)]


def find_rb_kana(text: str) -> list[str]:
    """[[rb:…]] の残り（中国語訳には不要。すべて外す）。"""
    return [m.group(0) for m in RB_ANY.finditer(text)]


def find_non_gbk_han(text: str) -> list[tuple[str, int]]:
    """GBK で表せない漢字 + EXTRA_NON_GB。簡体字訳に残ってはいけない字。"""
    counts: dict[str, int] = {}
    for ch in text:
        if not ("\u4e00" <= ch <= "\u9fff" or "\u3400" <= ch <= "\u4dbf" or "\uf900" <= ch <= "\ufaff"):
            continue
        if ch in EXTRA_NON_GB:
            counts[ch] = counts.get(ch, 0) + 1
            continue
        try:
            ch.encode("gbk")
        except UnicodeEncodeError:
            counts[ch] = counts.get(ch, 0) + 1
    return sorted(counts.items(), key=lambda kv: -kv[1])
